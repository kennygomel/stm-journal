// src/days.js — доплата за рабочие дни месяца.
//
// Таблица живёт и на сервере (tgcloud/lib/calc.js): модули tgcloud/ не видят src/,
// поэтому значения продублированы. Совпадение проверяет тест
// «таблица дней совпадает на клиенте и на сервере».
//
// День — это РАЗНАЯ дата рейса внутри календарного месяца; несколько рейсов
// в один день считаются одним рабочим днём. Сумма попадает в доход ровно один
// раз — в последнюю запись месяца (это делает сервер).

/** Число рабочих дней → доплата в КОПЕЙКАХ. */
export const DAYS_BONUS_TABLE = Object.freeze({
  23: 2500, // 25 ₽
  24: 5000, // 50 ₽
  25: 10000, // 100 ₽
  26: 15000, // 150 ₽
  27: 20000, // 200 ₽
  28: 25000, // 250 ₽
  29: 30000, // 300 ₽
  30: 40000, // 400 ₽
  31: 50000, // 500 ₽
});

/** С какого числа рабочих дней начинается доплата. */
export const DAYS_BONUS_MIN = 23;

/** Доплата за дни месяца в копейках (0, если дней меньше порога). */
export function daysBonusFor(dayCount) {
  const days = Math.floor(Number(dayCount) || 0);
  return DAYS_BONUS_TABLE[days] || 0;
}

/** Строки таблицы для экрана тарифов: [{ days, kopecks }] от 23 до 31. */
export function daysBonusRows() {
  return Object.keys(DAYS_BONUS_TABLE).map((days) => ({ days: Number(days), kopecks: DAYS_BONUS_TABLE[days] }));
}
